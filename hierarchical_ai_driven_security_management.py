def build_prototypes(E, y):
    protos = {}
    for cls in sorted(set(y)):
        m = np.array([v == cls for v in y])
        ce = E[m]
        if len(ce):
            p = ce.mean(0)
            protos[cls] = p / (np.linalg.norm(p) + 1e-8)
    return protos

